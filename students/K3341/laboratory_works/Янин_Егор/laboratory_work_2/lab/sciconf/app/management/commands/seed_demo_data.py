class Command(BaseCommand):
    help = "Create or update sample conferences, themes, and locations for demonstration."

    @transaction.atomic
    def handle(self, *args, **options):
        locations = {}
        for data in LOCATIONS:
            location, _ = Location.objects.update_or_create(
                name=data["name"],
                defaults={
                    "address": data["address"],
                    "description": data["description"],
                },
            )
            locations[location.name] = location

        themes = {}
        for name, description in THEMES:
            theme, _ = Theme.objects.update_or_create(
                name=name,
                defaults={"description": description},
            )
            themes[theme.name] = theme

        for data in CONFERENCES:
            conference, _ = Conference.objects.update_or_create(
                name=data["name"],
                defaults={
                    "description": data["description"],
                    "location": locations[data["location"]],
                    "start_date": data["start_date"],
                    "end_date": data["end_date"],
                    "participation_terms": data["participation_terms"],
                },
            )
            conference.themes.set(themes[name] for name in data["themes"])

        self.stdout.write(
            self.style.SUCCESS(
                f"Demo data ready: {len(CONFERENCES)} conferences, "
                f"{len(THEMES)} themes, {len(LOCATIONS)} locations."
            )
        )
